#!/usr/bin/env python3
"""Turn the Redmine sample dumps in docs/reference/ into loader-friendly CSV fixtures.

Why a parser and not "just run the SQL": the dumps are MySQL, the test database is
Oracle. Translating MySQL INSERT text to Oracle INSERT text drags in dialect,
identifier-quoting, backslash-escape and datetime-literal edge cases. Parsing once
into CSV and letting JDBC bind the values sidesteps all of that.

Two known defects in the dumps are handled here:

  (a) EMPTY TABLE NAME. Every statement reads ``INSERT INTO `` (...) VALUES (...)``
      -- the export tool dropped the table name. The real target is recovered from
      the FILENAME prefix (``01.`` -> issues, ``02.`` -> issue_statuses, ...).

  (b) WRONG FILTER COLUMN in ``05. redmine.custom_values.sql``. It was exported with
      ``WHERE id IN (<issue ids>)`` instead of ``WHERE customized_id IN (...)``, so its
      rows are arbitrary custom_values rows that happen to have those primary keys --
      they do not belong to the sampled issues at all. We filter custom_values to rows
      whose ``customized_id`` is in the issue id set and print the kept/total ratio so
      the defect is visible empirically rather than asserted from memory. In practice
      this prints ``custom_values: kept 0/23 rows``, which is why
      ``src/test/resources/fixtures/custom_values.csv`` is HAND-AUTHORED and tracked in
      git instead of being regenerated by this script.

NULL vs EMPTY STRING
--------------------
``custom_values.value`` is a MySQL ``longtext``. The report's SOLUTION classifier and
AGING_NEW both branch on "close date is NULL" vs "close date is the empty string", so
that distinction has to survive the dump -> CSV -> JDBC round trip. Plain CSV renders
both as an empty field, so this writer emits the sentinel ``\\N`` for SQL NULL and a
genuinely empty field for the empty string. MirrorFixtureLoader.bind() reverses the
mapping.
"""

from __future__ import annotations

import csv
import os
import re
import sys

# Defect (a): the dumps have an empty table name, so the target comes from the filename.
FILE_TABLE_MAP = [
    ("01.", "issues"),
    ("02.", "issue_statuses"),
    ("03.", "enumerations"),
    ("04.", "trackers"),
    ("05.", "custom_values"),
    ("06.", "journals"),
    ("07.", "journal_details"),
]

NULL_SENTINEL = "\\N"

INSERT_RE = re.compile(r"INSERT\s+INTO\s+`[^`]*`\s*\(", re.IGNORECASE)

# MySQL backslash escapes as emitted by HeidiSQL / mysqldump.
BACKSLASH_ESCAPES = {
    "0": "\0",
    "b": "\b",
    "n": "\n",
    "r": "\r",
    "t": "\t",
    "Z": "\x1a",
    "\\": "\\",
    "'": "'",
    '"': '"',
    "%": "\\%",  # MySQL leaves \% and \_ alone outside LIKE
    "_": "\\_",
}


class _Scanner:
    def __init__(self, text: str) -> None:
        self.text = text
        self.i = 0

    def skip_ws(self) -> None:
        while self.i < len(self.text) and self.text[self.i] in " \t\r\n":
            self.i += 1

    def read_identifier_list(self) -> list[str]:
        """Read ``col1`,`col2`,...)`` starting just after the opening paren."""
        cols: list[str] = []
        while True:
            self.skip_ws()
            if self.text[self.i] == ")":
                self.i += 1
                return cols
            if self.text[self.i] == ",":
                self.i += 1
                continue
            assert self.text[self.i] == "`", f"expected backtick at {self.i}"
            end = self.text.index("`", self.i + 1)
            cols.append(self.text[self.i + 1 : end])
            self.i = end + 1

    def read_value_tuple(self) -> list[str | None]:
        """Read ``val, val, ...)`` starting just after the opening paren.

        Returns Python ``None`` for SQL NULL and ``str`` for everything else, so the
        NULL / empty-string distinction is preserved all the way to the CSV writer.
        """
        values: list[str | None] = []
        while True:
            self.skip_ws()
            ch = self.text[self.i]
            if ch == ")":
                self.i += 1
                return values
            if ch == ",":
                self.i += 1
                continue
            if ch == "'":
                values.append(self._read_quoted())
            else:
                start = self.i
                while self.text[self.i] not in ",)":
                    self.i += 1
                token = self.text[start : self.i].strip()
                values.append(None if token.upper() == "NULL" else token)

    def _read_quoted(self) -> str:
        assert self.text[self.i] == "'"
        self.i += 1
        out: list[str] = []
        while True:
            ch = self.text[self.i]
            if ch == "\\":
                nxt = self.text[self.i + 1]
                out.append(BACKSLASH_ESCAPES.get(nxt, nxt))
                self.i += 2
            elif ch == "'":
                # '' inside a quoted literal is an escaped single quote.
                if self.i + 1 < len(self.text) and self.text[self.i + 1] == "'":
                    out.append("'")
                    self.i += 2
                else:
                    self.i += 1
                    return "".join(out)
            else:
                out.append(ch)
                self.i += 1


def parse_dump(path: str) -> tuple[list[str], list[list[str | None]]]:
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        text = fh.read()

    columns: list[str] = []
    rows: list[list[str | None]] = []

    for match in INSERT_RE.finditer(text):
        scanner = _Scanner(text)
        scanner.i = match.end()
        cols = scanner.read_identifier_list()
        if not columns:
            columns = cols
        elif cols != columns:
            raise SystemExit(f"{path}: inconsistent column list {cols} != {columns}")

        scanner.skip_ws()
        if not text[scanner.i :].upper().startswith("VALUES"):
            raise SystemExit(f"{path}: expected VALUES at offset {scanner.i}")
        scanner.i += len("VALUES")

        # A statement may carry several tuples: (..),(..),(..);
        while True:
            scanner.skip_ws()
            if scanner.text[scanner.i] != "(":
                break
            scanner.i += 1
            row = scanner.read_value_tuple()
            if len(row) != len(cols):
                raise SystemExit(
                    f"{path}: row has {len(row)} values for {len(cols)} columns"
                )
            rows.append(row)
            scanner.skip_ws()
            if scanner.text[scanner.i] == ",":
                scanner.i += 1
                continue
            break

    return columns, rows


def write_csv(out_path: str, columns: list[str], rows: list[list[str | None]]) -> None:
    with open(out_path, "w", encoding="utf-8", newline="") as fh:
        writer = csv.writer(fh, lineterminator="\n")
        writer.writerow(columns)
        for row in rows:
            writer.writerow([NULL_SENTINEL if v is None else v for v in row])


def main() -> int:
    here = os.path.dirname(os.path.abspath(__file__))
    repo_root = os.path.abspath(os.path.join(here, "..", "..", ".."))
    src_dir = os.path.join(repo_root, "docs", "reference")
    out_dir = os.path.join(here, "..", "src", "test", "resources", "fixtures")
    out_dir = os.path.abspath(out_dir)

    if len(sys.argv) > 1:
        src_dir = sys.argv[1]
    if len(sys.argv) > 2:
        out_dir = sys.argv[2]

    os.makedirs(out_dir, exist_ok=True)

    available = os.listdir(src_dir)
    issue_ids: set[str] = set()

    for prefix, table in FILE_TABLE_MAP:
        matches = [f for f in available if f.startswith(prefix) and f.endswith(".sql")]
        if not matches:
            print(f"{table}: SKIPPED (no dump matching '{prefix}*' in {src_dir})")
            continue
        path = os.path.join(src_dir, matches[0])
        columns, rows = parse_dump(path)
        total = len(rows)

        if table == "issues":
            id_idx = columns.index("id")
            issue_ids = {str(r[id_idx]) for r in rows}

        if table == "custom_values":
            # Defect (b): re-apply the filter the export should have used.
            cid_idx = columns.index("customized_id")
            rows = [r for r in rows if str(r[cid_idx]) in issue_ids]
            print(f"{table}: kept {len(rows)}/{total} rows")
            if not rows:
                print(
                    f"{table}: dump is unusable (exported on `id`, not `customized_id`) "
                    f"-- NOT overwriting the hand-authored fixture"
                )
                continue
        else:
            print(f"{table}: kept {total}/{total} rows")

        write_csv(os.path.join(out_dir, f"{table}.csv"), columns, rows)

    return 0


if __name__ == "__main__":
    raise SystemExit(main())

-- V13: adjustable parameters for the insight pages (RD 22524: "criteria to be decided by the user").
--
-- Three small tables, all editable from the Parameters menu (incident.params):
--   CFG_PARAM        scalar knobs (forecast, brand network, alert sample size)
--   CFG_ALERT_RULE   one row per alert rule: on/off, severity, minimum count, one threshold
--   CFG_CHANGE_LOG   who changed what, from and to (value-only; no ticket data)
-- The SLA ladder and at-risk cushion stay in CFG_SLA_POLICY (V1/V9); its V1 trigger already
-- re-derives the mart on the next refresh, so editing it here needs no extra plumbing.
--
-- DEFAULT_* columns hold the shipped value, so "reset to default" is a plain UPDATE from the UI.
-- None of these tables has a CFG_VERSION bump trigger: they never feed the mart.

CREATE TABLE CFG_PARAM (
    PARAM_KEY     VARCHAR2(64 CHAR)  NOT NULL,
    VALUE_TYPE    VARCHAR2(8 CHAR)   NOT NULL,
    PARAM_VALUE   VARCHAR2(64 CHAR)  NOT NULL,
    DEFAULT_VALUE VARCHAR2(64 CHAR)  NOT NULL,
    MIN_VALUE     NUMBER,
    MAX_VALUE     NUMBER,
    UPDATED_AT    TIMESTAMP(6)       DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_BY    VARCHAR2(64 CHAR),
    CONSTRAINT CFG_PARAM_PK PRIMARY KEY (PARAM_KEY),
    CONSTRAINT CFG_PARAM_TYPE_CK CHECK (VALUE_TYPE IN ('INT', 'DECIMAL', 'TEXT'))
);

CREATE TABLE CFG_ALERT_RULE (
    RULE_CODE         VARCHAR2(32 CHAR) NOT NULL,
    IS_ENABLED        NUMBER(1)         DEFAULT 1 NOT NULL,
    SEVERITY          VARCHAR2(8 CHAR)  NOT NULL,
    MIN_COUNT         NUMBER(5)         DEFAULT 1 NOT NULL,
    THRESHOLD         NUMBER(7, 2),
    DEFAULT_ENABLED   NUMBER(1)         NOT NULL,
    DEFAULT_SEVERITY  VARCHAR2(8 CHAR)  NOT NULL,
    DEFAULT_MIN_COUNT NUMBER(5)         NOT NULL,
    DEFAULT_THRESHOLD NUMBER(7, 2),
    UPDATED_AT        TIMESTAMP(6)      DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_BY        VARCHAR2(64 CHAR),
    CONSTRAINT CFG_ALERT_RULE_PK PRIMARY KEY (RULE_CODE),
    CONSTRAINT CFG_AR_ENABLED_CK CHECK (IS_ENABLED IN (0, 1)),
    CONSTRAINT CFG_AR_SEVERITY_CK CHECK (SEVERITY IN ('INFO', 'WARNING', 'HIGH', 'CRITICAL')),
    CONSTRAINT CFG_AR_MIN_COUNT_CK CHECK (MIN_COUNT >= 1)
);

CREATE TABLE CFG_CHANGE_LOG (
    ID         NUMBER GENERATED ALWAYS AS IDENTITY,
    CHANGED_AT TIMESTAMP(6)       DEFAULT SYSTIMESTAMP NOT NULL,
    CHANGED_BY VARCHAR2(64 CHAR)  NOT NULL,
    TARGET     VARCHAR2(80 CHAR)  NOT NULL,
    OLD_VALUE  VARCHAR2(200 CHAR),
    NEW_VALUE  VARCHAR2(200 CHAR),
    CONSTRAINT CFG_CHANGE_LOG_PK PRIMARY KEY (ID)
);

